package main

import (
	"go/ast"
	"go/parser"
	"go/token"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

func TestSuppress_Markers(t *testing.T) {
	root := testdataDir(t, "suppress/root")
	r, err := checkSuppress(t.Context(), testEnv(root), nil)
	if err != nil {
		t.Fatal(err)
	}
	// Every line marked want, and nothing else: the string literal "//nolint", prose
	// that mentions the markers, a generated-code line after the package clause, and the
	// nested testdata/ files pass. exact.lua writes its directives exactly as stylua and
	// luacheck honour them, which leaves no room for the marker, so its lines are listed
	// here: stylua's alone on an inner line of a long comment (5, 9) and after a no-break
	// space (12) or a vertical tab (14), and luacheck's after a vertical tab (18), also
	// right after the numeral 0xe (21), which Lua ends before the dashes.
	// unclosed.lua never closes a long comment, so it fails where the comment opens.
	want := append(wantLines(t, root), "exact.lua:5", "exact.lua:9", "exact.lua:12", "exact.lua:14", "exact.lua:18", "exact.lua:21")
	sort.Strings(want)
	sameLines(t, "suppressions", problemLines(t, r.problems), want, r.problems)
	for _, form := range []string{
		`"#noqa"`, `"# NOQA"`, `"flake8: noqa"`, `"#type:ignore"`, `"--luacheck:"`, `"//nolint:errcheck // want"`,
		`"///nolint:errcheck // want"`, `"// //nolint:errcheck // want"`, `"/*nolint:errcheck*/"`, `"//gosec:disable G304 -- want"`,
		`"# isort:"`, `"# ISORT:"`, `"# yapf:"`, `"--[[ stylua:"`, `"--[==[luacheck:"`, `"--[[STYLUA:"`,
		`gen.go:1:1: generated-code marker "// Code generated by a tool we want flagged. DO NOT EDIT."`,
		`exact.lua:5: inline suppression "stylua:"`, `exact.lua:18: inline suppression "luacheck:"`,
		`exact.lua:21: inline suppression "luacheck:"`,
		"unclosed.lua:2: comment: unterminated long bracket: trace cannot read the comments from here on",
	} {
		if countContaining(r.problems, form) != 1 {
			t.Errorf("the form %s is not reported once:\n%s", form, strings.Join(r.problems, "\n"))
		}
	}
	for _, text := range []string{
		"//nolint", "// nolint", "/* nolint */", "//lint:ignore x", "//lint:file-ignore x",
		"//exhaustive:ignore", "// NOLINT", "// see #nosec G101",
		"///nolint", "////nolint:gosec", "// //nolint:gosec", "// /nolint", "//\tnolint", "/*nolint*/",
		"/** nolint */", "/*\nnolint:errcheck\n*/", "/* //nolint */", "//gosec:disable G304", "// GOSEC:disable",
	} {
		if !goSuppression(text) {
			t.Errorf("goSuppression(%q) = false", text)
		}
	}
	for _, text := range []string{
		"// prose about nolint", "// lint is fine", "//go:build rltest", "// exhaustive switch",
		"/* prose about nolint */", "// gosec is a linter",
	} {
		if goSuppression(text) {
			t.Errorf("goSuppression(%q) = true", text)
		}
	}
	// generatedHeader reads the marker exactly as go/ast.IsGenerated does.
	for _, name := range []string{"a.go", "gen.go"} {
		f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, name), nil, parser.ParseComments)
		if err != nil {
			t.Fatal(err)
		}
		if got := generatedHeader(f) != nil; got != ast.IsGenerated(f) || got != (name == "gen.go") {
			t.Errorf("%s: generatedHeader found a marker = %v, ast.IsGenerated = %v", name, got, ast.IsGenerated(f))
		}
	}
}
